//! The operator registry. `recordchaos operators list` and docs/operators.md
//! are generated from it.

use super::{
    Operator, bundle_ops, identifier, medication, observation, quantity, reference, resource_ops,
    text, time_ops,
};
use crate::validate::Layer;

/// All 22 operators, in the spec's order.
pub static REGISTRY: [Operator; 22] = [
    observation::DUPLICATE_WITH_CHANGED_ISSUED,
    observation::CORRECTION_SEQUENCE,
    identifier::DUPLICATE_BUSINESS_IDENTIFIER,
    medication::CONFLICTING_ACTIVE_REQUESTS,
    time_ops::BACKDATE_EFFECTIVE,
    time_ops::FUTURE_EFFECTIVE,
    time_ops::DATE_ONLY_PRECISION,
    time_ops::TIMEZONE_OFFSET_SHIFT,
    time_ops::PERIOD_END_BEFORE_START,
    quantity::EQUIVALENT_UNIT,
    quantity::REMOVE_UNIT_CODE,
    observation::DATA_ABSENT_REASON,
    observation::REMOVE_CODE,
    observation::REMOVE_STATUS,
    reference::TO_URN_UUID,
    reference::TO_ABSOLUTE_URL,
    reference::DANGLING_TARGET,
    reference::CROSS_PATIENT,
    bundle_ops::REORDER_ENTRIES,
    bundle_ops::DUPLICATE_FULL_URL,
    resource_ops::UNEXPECTED_TYPE,
    text::UNICODE_NARRATIVE,
];

/// Find an operator by id.
pub fn find(id: &str) -> Option<&'static Operator> {
    REGISTRY.iter().find(|op| op.info.id == id)
}

fn layers_text(layers: &[Layer], strict_rule: Option<&str>) -> String {
    if layers.is_empty() {
        return String::from("none");
    }
    let names: Vec<String> = layers
        .iter()
        .map(|l| match (l, strict_rule) {
            (Layer::Strict, Some(rule)) => format!("strict ({rule})"),
            (other, _) => other.name().to_string(),
        })
        .collect();
    let text = names.join(", ");
    if layers == [Layer::Strict] {
        format!("strict only: {}", strict_rule.unwrap_or("HL7 validator"))
    } else {
        text
    }
}

/// Text for the "Caught by" column.
pub fn caught_by_text(op: &Operator) -> String {
    layers_text(op.info.caught_by, op.info.strict_rule)
}

/// docs/operators.md, generated from the registry.
pub fn markdown_doc() -> String {
    let mut out = String::new();
    out.push_str("# Operators\n\n");
    out.push_str("Generated by `recordchaos operators list --format markdown` from the operator registry. Do not edit by hand.\n\n");
    out.push_str("| # | Operator | What it does | Intended | Caught by | Effect on the view |\n");
    out.push_str("|---|---|---|---|---|---|\n");
    for op in REGISTRY.iter() {
        let i = &op.info;
        out.push_str(&format!(
            "| {} | `{}` | {} | {} | {} | {} |\n",
            i.number,
            i.id,
            i.summary,
            i.intent.label(),
            caught_by_text(op),
            i.view_effect
        ));
    }
    out.push('\n');
    out.push_str("The R4 JSON schema requires only `code` and `resourceType` on Observation and does not require `status`; it has no check that a period starts before it ends. That is why operators 9 and 14 are strict only. Without `--strict`, their cases are reported as not checked at that layer, never as valid or invalid.\n");
    for op in REGISTRY.iter() {
        let i = &op.info;
        out.push_str(&format!("\n## {}. `{}`\n\n", i.number, i.id));
        out.push_str(&format!("{}.\n\n", i.summary));
        out.push_str(&format!("- Version: {}\n", i.version));
        out.push_str(&format!("- Intended: {}\n", i.intent.label()));
        out.push_str(&format!("- Caught by: {}\n", caught_by_text(op)));
        out.push_str(&format!("- Effect on the view: {}\n", i.view_effect));
        out.push_str(&format!("- Eligible targets: {}\n", i.eligibility));
        out.push_str(&format!("- Paths it may change: {}\n", i.paths));
        out.push_str(&format!("- Reversible: {}\n", i.reversible));
        if i.args.is_empty() {
            out.push_str("- Arguments: none\n");
        } else {
            out.push_str("- Arguments:\n");
            for a in i.args {
                out.push_str(&format!(
                    "  - `{}` (default `{}`): {}\n",
                    a.name, a.default, a.help
                ));
            }
        }
        out.push_str(&format!(
            "\nBefore:\n\n```text\n{}\n```\n\nAfter:\n\n```text\n{}\n```\n",
            i.before, i.after
        ));
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::collections::BTreeSet;

    #[test]
    fn registry_has_22_unique_operators_in_order() {
        let ids: BTreeSet<&str> = REGISTRY.iter().map(|o| o.info.id).collect();
        assert_eq!(ids.len(), 22);
        for (i, op) in REGISTRY.iter().enumerate() {
            assert_eq!(usize::from(op.info.number), i + 1, "{}", op.info.id);
        }
    }

    #[test]
    fn markdown_lists_every_operator() {
        let doc = markdown_doc();
        for op in REGISTRY.iter() {
            assert!(doc.contains(op.info.id));
        }
    }

    #[test]
    fn docs_file_mentions_every_operator() {
        let path = concat!(env!("CARGO_MANIFEST_DIR"), "/../../docs/operators.md");
        let text = std::fs::read_to_string(path).unwrap();
        for op in REGISTRY.iter() {
            assert!(
                text.contains(op.info.id),
                "docs/operators.md is missing {}",
                op.info.id
            );
        }
    }
}
